/**
 * התקנת טריגרים על בסיס אופציה 2
 * פורמט: {{שם_פונקציה, סוג_זמן, מספר}} - סוג_זמן יכול להיות "Hours" או "Minutes"
 */
function התקן_טריגרים() {
  const הגדרות = קרא_הגדרות();
  
  // מחיקת טריגרים ישנים במידה והתבקש
  if (הגדרות[111] === 'כן') {
    const טריגרים_קיימים = ScriptApp.getProjectTriggers();
    for (let i = 0; i < טריגרים_קיימים.length; i++) {
      ScriptApp.deleteTrigger(טריגרים_קיימים[i]);
    }
  }

  // עוברים על מפתחות 112 עד 116 (טריגר 1 עד 5)
  for (let מפתח = 112; מפתח <= 116; מפתח++) {
    const טקסט_טריגר = הגדרות[מפתח];
    if (טקסט_טריגר) {
      // חילוץ נתונים בעזרת Regex, מצפה לפורמט: {{שם, סוג, מספר}}
      const תבנית = /\{\{\s*([^,]+)\s*,\s*([^,]+)\s*,\s*(\d+)\s*\}\}/;
      const התאמה = טקסט_טריגר.match(תבנית);
      
      if (התאמה) {
        const שם_פונקציה = התאמה[1].trim();
        const סוג_זמן = התאמה[2].trim();
        const מספר_זמן = parseInt(התאמה[3].trim(), 10);
        
        try {
          const בונה_טריגר = ScriptApp.newTrigger(שם_פונקציה).timeBased();
          
          if (סוג_זמן.toLowerCase() === "hours") {
            בונה_טריגר.everyHours(מספר_זמן);
          } else if (סוג_זמן.toLowerCase() === "minutes") {
            בונה_טריגר.everyMinutes(מספר_זמן);
          }
          
          בונה_טריגר.create();
        } catch (שגיאה) {
          console.error("שגיאה ביצירת טריגר עבור: " + טקסט_טריגר, שגיאה);
        }
      }
    }
  }
}