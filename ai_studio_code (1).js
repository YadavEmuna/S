/**
 * משהה את ריצת הסקריפט לפי כמות שניות
 */
function השהיה_בין_שלבים(שניות) {
  if (שניות && שניות > 0) {
    Utilities.sleep(שניות * 1000);
  }
}

/**
 * מחליף משתנים דינמיים בטקסט (כגון {פרשה} ו-{שנה})
 */
function החלף_משתנים(טקסט, משתנים) {
  if (!טקסט) return "";
  let טקסט_חדש = טקסט;
  if (משתנים.פרשה) טקסט_חדש = טקסט_חדש.replace(/{פרשה}/g, משתנים.פרשה);
  if (משתנים.שנה) טקסט_חדש = טקסט_חדש.replace(/{שנה}/g, משתנים.שנה);
  return טקסט_חדש;
}

/**
 * פונקציה חכמה לשליחת מייל. בודקת האם לשלב בשרשור קיים בעל אותו נושא, או לפתוח חדש.
 */
function שלח_מייל(כתובת, נושא, גוף_הודעה, קבצים_מצורפים, האם_לשלב_בשרשור) {
  const אפשרויות = {};
  if (קבצים_מצורפים && קבצים_מצורפים.length > 0) {
    אפשרויות.attachments = קבצים_מצורפים;
  }

  if (האם_לשלב_בשרשור === 'כן') {
    // חיפוש שרשור קיים לפי נושא מדויק
    const שרשורים = GmailApp.search('subject:"' + נושא + '" to:' + כתובת, 0, 1);
    if (שרשורים.length > 0) {
      שרשורים[0].replyAll(גוף_הודעה, אפשרויות);
      return;
    }
  }
  
  // אם לא נמצא שרשור או שלא הוגדר לשלב, שולחים כמייל חדש
  GmailApp.sendEmail(כתובת, נושא, גוף_הודעה, אפשרויות);
}

/**
 * הוספת תווית לשרשור (יוצר את התווית אם היא לא קיימת)
 */
function הוסף_תווית(שרשור, שם_תווית) {
  if (!שם_תווית) return;
  let תווית = GmailApp.getUserLabelByName(שם_תווית);
  if (!תווית) {
    תווית = GmailApp.createLabel(שם_תווית);
  }
  שרשור.addLabel(תווית);
}

/**
 * הסרת תווית משרשור
 */
function הסר_תווית(שרשור, שם_תווית) {
  if (!שם_תווית) return;
  const תווית = GmailApp.getUserLabelByName(שם_תווית);
  if (תווית) {
    שרשור.removeLabel(תווית);
  }
}

/**
 * טיפול במיילים חוזרים (נכנסים) מכתובת מסוימת לפי הגדרות
 */
function נקה_מיילים_נכנסים(כתובת, האם_לקרוא, האם_לארכיון, האם_למחוק) {
  if (!כתובת) return;
  const שרשורים = GmailApp.search('from:' + כתובת + ' is:unread');
  
  for (let i = 0; i < שרשורים.length; i++) {
    const שרשור = שרשורים[i];
    if (האם_לקרוא === 'כן') שרשור.markRead();
    if (האם_לארכיון === 'כן') שרשור.moveToArchive();
    if (האם_למחוק === 'כן') שרשור.moveToTrash();
  }
}