/**
 * שלב 3: דרייב
 */
function בצע_שלב_דרייב(הגדרות, שרשור, קובץ_אודיו, דוח) {
  let קישור_דרייב = "";
  
  if (הגדרות[38] !== 'כן') {
    if (הגדרות[42] === 'כן') הוסף_תווית(שרשור, הגדרות[43]);
    דוח.push("שלב 3 (דרייב): דולג.");
    return קישור_דרייב;
  }

  try {
    const מזהה_תיקיה = הגדרות[39];
    if (מזהה_תיקיה) {
      const תיקיה = DriveApp.getFolderById(מזהה_תיקיה);
      const קובץ_חדש = תיקיה.createFile(קובץ_אודיו);
      קישור_דרייב = קובץ_חדש.getUrl();
      
      if (הגדרות[40] === 'כן') הוסף_תווית(שרשור, הגדרות[41]);
      דוח.push("שלב 3 (דרייב): הקובץ הועלה בהצלחה. קישור: " + קישור_דרייב);
    } else {
      דוח.push("שלב 3 (דרייב): נכשל - לא הוגדר מזהה תיקיה.");
    }
  } catch (שגיאה) {
    if (הגדרות[44] === 'כן') הוסף_תווית(שרשור, הגדרות[45]);
    דוח.push("שגיאה בשלב 3 (דרייב): " + שגיאה.message);
  }
  
  return קישור_דרייב;
}