/**
 * פונקציה ראשית המנהלת את כל התהליך (זו הפונקציה שמופעלת מהטריגר)
 */
function הפעל_מערכת() {
  const הגדרות = קרא_הגדרות();
  let דוח_ריצה = [];
  
  // שלב 1: חיפוש ונעילה
  const תוצאת_חיפוש = חפש_ונעל_מייל(הגדרות);
  if (!תוצאת_חיפוש) {
    if (הגדרות[5] === 'כן') console.log("לא נמצאו מיילים חדשים לעיבוד.");
    return; // סיום הריצה
  }
  
  const { שרשור, הודעה, תווית_עיבוד, תווית_אבא } = תוצאת_חיפוש;
  דוח_ריצה.push("התחיל עיבוד של שרשור: " + שרשור.getFirstMessageSubject());

  // חילוץ קובץ האודיו מתוך ההודעה
  const צרוxxx = הודעה.getAttachments();
  let קובץ_אודיו = null;
  for (let i = 0; i < צרופות.length; i++) {
    const סוג = צרופות[i].getContentType();
    const שם = צרופות[i].getName().toLowerCase();
    if (סוג.includes('audio') || שם.endsWith('mp3') || שם.endsWith('wav') || שם.endsWith('m4a') || שם.endsWith('ogg') || שם.endsWith('amr')) {
      קובץ_אודיו = צרופות[i];
      break;
    }
  }

  if (!קובץ_אודיו) {
    דוח_ריצה.push("שגיאה: לא נמצא קובץ אודיו בהודעה למרות שהיא סוננה.");
    הסר_תווית(שרשור, תווית_עיבוד);
    // נסמן בתווית נכשל כללית אם נרצה
    return;
  }

  // שלב 7: חישוב תאריך עברי (הכנת המשתנים {שנה} ו-{פרשה})
  const משתנים = חשב_תאריך_עברי(הודעה, דוח_ריצה);
  
  const שניות_המתנה = הגדרות[4] ? parseInt(הגדרות[4], 10) : 0;

  // שלב 2: גרופס
  השהיה_בין_שלבים(שניות_המתנה);
  בצע_שלב_גרופס(הגדרות, שרשור, קובץ_אודיו, משתנים, דוח_ריצה);
  
  // שלב 3: דרייב
  השהיה_בין_שלבים(שניות_המתנה);
  const קישור_דרייב = בצע_שלב_דרייב(הגדרות, שרשור, קובץ_אודיו, דוח_ריצה);
  
  // שלב 4: צ'אט
  השהיה_בין_שלבים(שניות_המתנה);
  בצע_שלב_צאט(הגדרות, שרשור, קישור_דרייב, משתנים, דוח_ריצה);
  
  // שלב 5: תמלול
  השהיה_בין_שלבים(שניות_המתנה);
  בצע_שלב_תמלול(הגדרות, שרשור, קובץ_אודיו, משתנים, דוח_ריצה);
  
  // סיום: הסרת תווית העיבוד והוספת "תווית האבא" הקבועה
  הסר_תווית(שרשור, תווית_עיבוד);
  הוסף_תווית(שרשור, תווית_אבא);
  דוח_ריצה.push("סיום תהליך: המייל סומן בתווית האבא ולעולם לא יעובד שוב.");

  // הדפסה ללוג גוגל (אם מוגדר)
  if (הגדרות[5] === 'כן') {
    console.log(דוח_ריצה.join("\n"));
  }

  // שלב 6: דוח מפורט
  השהיה_בין_שלבים(שניות_המתנה);
  שלח_דוח(הגדרות, דוח_ריצה, משתנים);
}