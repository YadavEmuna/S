/**
 * שלב 4: צ'אט
 */
function בצע_שלב_צאט(הגדרות, שרשור, קישור_דרייב, משתנים, דוח) {
  if (הגדרות[48] !== 'כן') {
    if (הגדרות[55] === 'כן') הוסף_תווית(שרשור, הגדרות[56]);
    דוח.push("שלב 4 (צ'אט): דולג.");
    return;
  }

  try {
    const כתובת = הגדרות[49];
    const האם_לשלב = הגדרות[50];
    const נושא = החלף_משתנים(הגדרות[51], משתנים);
    const גוף = החלף_משתנים(הגדרות[52], משתנים);
    
    let קבצים_מצורפים = [];
    if (קישור_דרייב) {
      // יצירת קובץ דמה (ריק) שהשם שלו הוא הקישור מהדרייב (ללא סיומת)
      const קובץ_דמה = Utilities.newBlob('', 'application/octet-stream', קישור_דרייב);
      קבצים_מצורפים.push(קובץ_דמה);
    }

    if (כתובת) {
      שלח_מייל(כתובת, נושא, גוף, קבצים_מצורפים, האם_לשלב);
      if (הגדרות[53] === 'כן') הוסף_תווית(שרשור, הגדרות[54]);
      דוח.push("שלב 4 (צ'אט): בוצע בהצלחה ונשלח קובץ דמה.");
      
      נקה_מיילים_נכנסים(כתובת, הגדרות[59], הגדרות[60], הגדרות[61]);
    } else {
      דוח.push("שלב 4 (צ'אט): נכשל - חסרה כתובת מייל.");
    }
  } catch (שגיאה) {
    if (הגדרות[57] === 'כן') הוסף_תווית(שרשור, הגדרות[58]);
    דוח.push("שגיאה בשלב 4 (צ'אט): " + שגיאה.message);
  }
}