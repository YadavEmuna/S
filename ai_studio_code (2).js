/**
 * שלב 1: זיהוי ונעילת המייל
 */
function חפש_ונעל_מייל(הגדרות) {
  let שאילתה = "has:attachment filename:(mp3 OR wav OR ogg OR m4a OR amr) "; // חובה קובץ אודיו (מפתח 17 מניח תמיד קיום אודיו במערכת זו)

  if (הגדרות[9]) שאילתה += "from:(" + הגדרות[9] + ") ";
  if (הגדרות[10]) שאילתה += "to:(" + הגדרות[10] + ") ";
  if (הגדרות[11]) שאילתה += "subject:(" + הגדרות[11] + ") ";
  if (הגדרות[12]) שאילתה += '="' + הגדרות[12] + '" '; // תוכן
  if (הגדרות[13]) שאילתה += "label:" + הגדרות[13] + " ";
  if (הגדרות[14]) שאילתה += "-subject:(" + הגדרות[14] + ") ";
  if (הגדרות[15]) שאילתה += '-"' + הגדרות[15] + '" ';
  if (הגדרות[16]) שאילתה += "-label:" + הגדרות[16] + " ";
  
  // חובה להתעלם ממיילים שכבר קיבלו את "תווית האבא" הקבועה או שנמצאים בעיבוד כעת
  const תווית_אבא = "טופל_בהצלחה_אבא";
  const תווית_עיבוד = "מעבד_כעת";
  שאילתה += "-label:" + תווית_אבא + " -label:" + תווית_עיבוד + " is:unread";

  const שרשורים = GmailApp.search(שאילתה, 0, 1);
  
  if (שרשורים.length === 0) {
    return null; // לא נמצאו מיילים מתאימים
  }

  const שרשור = שרשורים[0];
  const הודעות = שרשור.getMessages();
  const הודעה_אחרונה = הודעות[הודעות.length - 1]; // ניקח את ההודעה האחרונה בשרשור

  // יישום LockService כדי למנוע כפילויות ריצה בו זמנית
  const מנעול = LockService.getScriptLock();
  try {
    מנעול.waitLock(10000); // ממתין עד 10 שניות
    
    // סימון מיידי שמונע מסקריפטים מקבילים לגעת במייל
    הוסף_תווית(שרשור, תווית_עיבוד);
    
    return {
      שרשור: שרשור,
      הודעה: הודעה_אחרונה,
      תווית_עיבוד: תווית_עיבוד,
      תווית_אבא: תווית_אבא
    };
  } catch (e) {
    console.error("שגיאת נעילה: לא ניתן לנעול את הסקריפט לעיבוד המייל.", e);
    return null;
  } finally {
    מנעול.releaseLock();
  }
}