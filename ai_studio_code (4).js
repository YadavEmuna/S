/**
 * שלב 2: גרופס
 */
function בצע_שלב_גרופס(הגדרות, שרשור, קובץ_אודיו, משתנים, דוח) {
  if (הגדרות[22] !== 'כן') {
    if (הגדרות[29] === 'כן') הוסף_תווית(שרשור, הגדרות[30]);
    דוח.push("שלב 2 (גרופס): דולג (מוגדר כ'לא').");
    return;
  }

  try {
    const כתובת_קבוצה = הגדרות[23];
    const האם_לשלב = הגדרות[24];
    const נושא = החלף_משתנים(הגדרות[25], משתנים);
    const גוף = החלף_משתנים(הגדרות[26], משתנים);
    
    if (כתובת_קבוצה) {
      שלח_מייל(כתובת_קבוצה, נושא, גוף, [קובץ_אודיו], האם_לשלב);
      if (הגדרות[27] === 'כן') הוסף_תווית(שרשור, הגדרות[28]);
      דוח.push("שלב 2 (גרופס): המייל נשלח לקבוצה בהצלחה.");
      
      // טיפול במיילים חוזרים מהקבוצה
      נקה_מיילים_נכנסים(כתובת_קבוצה, הגדרות[33], הגדרות[34], הגדרות[35]);
    } else {
      דוח.push("שלב 2 (גרופס): נכשל - לא הוגדרה כתובת קבוצה.");
    }
  } catch (שגיאה) {
    if (הגדרות[31] === 'כן') הוסף_תווית(שרשור, הגדרות[32]);
    דוח.push("שגיאה בשלב 2 (גרופס): " + שגיאה.message);
  }
}