/**
 * שלב 6: שליחת דוח מצב מסכם
 */
function שלח_דוח(הגדרות, דוח, משתנים) {
  if (הגדרות[89] !== 'כן') {
    return;
  }

  try {
    const כתובת = הגדרות[90];
    const האם_לשלב = הגדרות[91];
    const נושא = החלף_משתנים(הגדרות[92], משתנים);
    let גוף = החלף_משתנים(הגדרות[93], משתנים) + "\n\nפירוט השלבים:\n";
    
    גוף += דוח.join("\n");

    if (כתובת) {
      שלח_מייל(כתובת, נושא, גוף, [], האם_לשלב);
      נקה_מיילים_נכנסים(כתובת, הגדרות[94], הגדרות[95], הגדרות[96]);
    }
  } catch (שגיאה) {
    console.error("שגיאה בשליחת הדוח: " + שגיאה.message);
  }
}