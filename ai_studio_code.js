/**
 * קורא את ההגדרות מגיליון ה-Google Sheets הנוכחי.
 * מחזיר אובייקט שבו המפתחות הם מספרי מזהה (עמודה C) והערכים הם הערכים (עמודה D).
 * ערכים ריקים יקבלו null.
 */
function קרא_הגדרות() {
  const גיליון = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();
  const נתונים = גיליון.getDataRange().getValues();
  let הגדרות = {};

  // עוברים על כל השורות בגיליון
  for (let i = 0; i < נתונים.length; i++) {
    const שורה = נתונים[i];
    const מפתח = שורה[2]; // עמודה C (אינדקס 2)
    const ערך = שורה[3];  // עמודה D (אינדקס 3)

    if (מפתח !== "" && מפתח !== null) {
      // אם הערך ריק נגדיר אותו כ-null, אחרת נשמור את הערך
      הגדרות[מפתח] = (ערך !== "" && ערך !== null) ? ערך : null;
    }
  }
  
  return הגדרות;
}